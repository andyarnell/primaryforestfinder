// ── Lookup helper ─────────────────────────────────────
/**
 * Get FRA forest area, primary forest, and naturally regenerating forest for a country and year.
 * @param {string} countryName  GAUL 2024 country name
 * @param {number} year  Target year (1990, 2000, 2010, 2015, 2020)
 * @return {{forestArea: number|null, primaryForest: number|null, naturalForest: number|null}}
 *         Values in 1000 ha, or null if not reported.
 */
exports.getFRA = function(countryName, year) {
  var fa = FRA_FOREST_AREA[countryName];
  var pf = FRA_PRIMARY_FOREST[countryName];
  var nf = FRA_NATURAL_FOREST[countryName];
  return {
    forestArea: (fa && fa[year] !== undefined) ? fa[year] : null,
    primaryForest: (pf && pf[year] !== undefined) ? pf[year] : null,
    naturalForest: (nf && nf[year] !== undefined) ? nf[year] : null
  };
};

// ── Convenience: format for display ───────────────────
/**
 * Format FRA stats as a display string.
 * @param {string} countryName  GAUL 2024 country name
 * @param {number} year  Target year
 * @return {string}  e.g. "FRA: 502,366.9 kha forest, 228,319.5 kha primary, 274,663.3 kha natural"
 *                   or "FRA: not reported"
 */
exports.formatFRA = function(countryName, year) {
  var d = exports.getFRA(countryName, year);
  if (d.forestArea === null && d.primaryForest === null && d.naturalForest === null) {
    return "FRA (" + year + "): not reported";
  }
  var parts = [];
  if (d.forestArea !== null) {
    parts.push(d.forestArea.toLocaleString() + " kha forest");
  }
  if (d.naturalForest !== null) {
    parts.push(d.naturalForest.toLocaleString() + " kha natural");
  }
  if (d.primaryForest !== null) {
    parts.push(d.primaryForest.toLocaleString() + " kha primary");
  } else {
    parts.push("primary: not reported");
  }
  return "FRA (" + year + "): " + parts.join(", ");
};

